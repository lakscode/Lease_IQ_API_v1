// Train the lease clause classifier (TF-IDF + one-vs-rest linear SVM) in TypeScript. Usage: npm run svm:train
//
// Inputs   svm/training_data/*.xlsx   column A = clause text, column B = clause id ("__label__<id>" or bare "<id>")
//          svm/lease_clauses.json     {clause id: clause name}; rows whose id is not listed are skipped
// Outputs  supabase/functions/api/lib/clause-svm-model.ts     model used by lib/clause-svm.ts (Node + Edge; generated, don't edit)
//          svm/training_examples.json                        the deduplicated examples; also uploaded to the database
//                                                             (clause_training_sets 'base') when API/.env is set, for
//                                                             Settings → Train model, which retrains with users' clauses
//          supabase/functions/api/lib/lease-clauses.ts        clause id → name map (also used by the LangChain classifier)
//          svm/training_report.json                           cross-validated metrics, per-clause scores, skipped labels
//
// The algorithm is in lib/clause-svm-train.ts (shared with the browser trainer) and the features in
// lib/clause-svm-features.ts (shared with prediction), so training and prediction can't drift apart.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { NGRAM_RANGE } from '../supabase/functions/api/lib/clause-svm-features.ts';
import { prepareExamples, rng, TRAIN_CONFIG, trainModel, type Example } from '../supabase/functions/api/lib/clause-svm-train.ts';
import { readXlsx } from './xlsx-read.ts';
import 'dotenv/config';

const API_DIR = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA_DIR = join(API_DIR, 'svm', 'training_data');
const CLAUSE_MAP = join(API_DIR, 'svm', 'lease_clauses.json');
const LIB = join(API_DIR, 'supabase', 'functions', 'api', 'lib');
const MODEL_OUT = join(LIB, 'clause-svm-model.ts');
const DATA_OUT = join(API_DIR, 'svm', 'training_examples.json');
const CLAUSES_OUT = join(LIB, 'lease-clauses.ts');
const REPORT_OUT = join(API_DIR, 'svm', 'training_report.json');

function loadRows(): { rows: Example[]; fileOf: Map<Example, string> } {
  const rows: Example[] = [];
  const fileOf = new Map<Example, string>();
  const files = readdirSync(DATA_DIR).filter((f) => f.toLowerCase().endsWith('.xlsx') && !f.startsWith('~$')).sort();
  for (const file of files) {
    for (const sheet of readXlsx(join(DATA_DIR, file))) {
      for (const [text, label] of sheet.rows) {
        const row = { text: text ?? '', label: label ?? '' };
        rows.push(row);
        fileOf.set(row, file);
      }
    }
  }
  return { rows, fileOf };
}

/**
 * Generated modules export JSON text: the Supabase Edge bundler only includes statically imported modules (a .json file
 * loaded with a dynamic import is left out), and parsing stays lazy.
 */
const jsonModule = (name: string, json: string) =>
  '// Generated by scripts/svm-train.ts (npm run svm:train). Do not edit.\n' +
  `export const ${name} = ${JSON.stringify(json)};\n`;

const started = Date.now();
const clauseMap = JSON.parse(readFileSync(CLAUSE_MAP, 'utf8')) as Record<string, string>;
const { rows, fileOf } = loadRows();
const { examples, skipped } = prepareExamples(rows, clauseMap);
const counts = new Map<string, number>();
for (const e of examples) counts.set(e.label, (counts.get(e.label) ?? 0) + 1);
console.log(`${examples.length} unique examples, ${counts.size} clause types ` +
  `(${[...skipped.values()].reduce((a, b) => a + b, 0)} rows skipped: ${skipped.size} ids not in lease_clauses.json)`);

const result = trainModel(examples, clauseMap, (p) => {
  if (p.stage === 'cv' && p.step > 0) console.log(`  fold ${p.step}/${TRAIN_CONFIG.cvFolds} done (${((Date.now() - started) / 1000).toFixed(0)}s)`);
  if (p.stage === 'final') console.log(`  fold ${TRAIN_CONFIG.cvFolds}/${TRAIN_CONFIG.cvFolds} done; training the final model`);
});
const { model, cross_validation: cv } = result;
console.log(`${cv.folds}-fold CV on ${cv.examples} examples: accuracy ${cv.accuracy.toFixed(3)}, macro F1 ${cv.macro_f1.toFixed(3)}, temperature ${model.temperature.toFixed(2)}`);
for (const r of cv.calibration) console.log(`  confidence >= ${r.min_confidence.toFixed(1)}: coverage ${(r.coverage * 100).toFixed(1)}%, accuracy ${((r.accuracy ?? 0) * 100).toFixed(1)}%`);

writeFileSync(MODEL_OUT, jsonModule('MODEL_JSON', JSON.stringify(model)));
const trainingJson = JSON.stringify({ trained_at: model.trained_at, examples: examples.map((e) => [e.text, e.label]) });
writeFileSync(DATA_OUT, trainingJson);
writeFileSync(CLAUSES_OUT,
  '// Generated from svm/lease_clauses.json by scripts/svm-train.ts (npm run svm:train). Do not edit.\n' +
  '// Clause id → name: the taxonomy of the SVM and LangChain (Llama) clause classifiers.\n' +
  `export const LEASE_CLAUSES: Record<string, string> = {\n${Object.entries(clauseMap).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},\n`).join('')}};\n`);

// Reference predictions from the in-memory model; svm:check confirms the exported JSON reproduces them.
const random = rng(TRAIN_CONFIG.seed + 1);
const parity = Array.from({ length: 25 }, () => examples[Math.floor(random() * examples.length)]).map((e) => ({ text: e.text, ...result.predict(e.text) }));

const firstFile = new Map<string, string>();
for (const r of rows) {
  const key = `${r.label.trim().replace(/^__label__/, '').trim()}\u0000${r.text.trim()}`;
  if (!firstFile.has(key)) firstFile.set(key, fileOf.get(r)!);
}
const perFile = new Map<string, number>();
for (const e of examples) {
  const file = firstFile.get(`${e.label}\u0000${e.text}`) ?? '?';
  perFile.set(file, (perFile.get(file) ?? 0) + 1);
}
const untrained = Object.fromEntries(Object.entries(clauseMap).filter(([id]) => !counts.has(id)));
const report = {
  trained_at: model.trained_at,
  trainer: 'scripts/svm-train.ts',
  examples: examples.length,
  clause_types: model.classes.length,
  config: { ngram_range: NGRAM_RANGE, min_df: TRAIN_CONFIG.minDf, max_features: TRAIN_CONFIG.maxFeatures, C: TRAIN_CONFIG.C, class_weight: 'balanced', eps: TRAIN_CONFIG.eps, prune_below: TRAIN_CONFIG.pruneBelow },
  model_nonzero_weights: result.nonzero_weights,
  cross_validation: cv,
  per_clause: result.per_clause,
  clauses_without_training_data: untrained,
  skipped_labels_not_in_lease_clauses_json: Object.fromEntries([...skipped].sort((a, b) => b[1] - a[1])),
  examples_per_file: Object.fromEntries([...perFile].map(([f, n]) => [basename(f), n])),
  parity_samples: parity,
};
writeFileSync(REPORT_OUT, JSON.stringify(report, null, 2));

const kb = (f: string) => Math.round(statSync(f).size / 1024).toLocaleString();
console.log(`model: ${model.terms.length} terms, ${result.nonzero_weights} weights, ${kb(MODEL_OUT)} KB -> ${MODEL_OUT}`);
console.log(`training examples: ${kb(DATA_OUT)} KB -> ${DATA_OUT}`);
// The training examples go to the database (not the Edge bundle, which has a size limit) for Settings → Train model.
if (process.env.SUPABASE_URL && process.env.SUPABASE_SERVICE_ROLE_KEY) {
  const { db } = await import('../supabase/functions/api/lib/supabase.ts');
  const { error } = await db().from('clause_training_sets')
    .upsert({ name: 'base', data: trainingJson, examples: examples.length, updated_at: new Date().toISOString() });
  console.log(error ? `training examples NOT uploaded: ${error.message}` : 'training examples uploaded to the database (clause_training_sets: base)');
} else {
  console.log('training examples not uploaded (no SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY); Settings → Train model keeps the previous set');
}
console.log(`report -> ${REPORT_OUT} (${((Date.now() - started) / 1000).toFixed(0)}s)`);
if (Object.keys(untrained).length) console.log(`${Object.keys(untrained).length} clause types in lease_clauses.json have no training data: ${Object.values(untrained).join(', ')}`);
